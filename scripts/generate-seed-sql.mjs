// Regenerates supabase/seed.sql from src/data/seed.json so the DB seed and the
// no-Supabase fallback in the app never drift. Run: node scripts/generate-seed-sql.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { restaurants } = JSON.parse(readFileSync(join(root, "src/data/seed.json"), "utf8"));

const q = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(", ")}]::text[]`;

let sql = `-- Generated by scripts/generate-seed-sql.mjs from src/data/seed.json — do not edit by hand.
-- Run after schema.sql. Safe to re-run: it wipes and re-inserts the catalogue.

delete from public.menu_items;
delete from public.restaurants;

`;

for (const r of restaurants) {
  sql += `with r as (
  insert into public.restaurants (slug, name, cuisine_tags, rating, rating_count, delivery_min_minutes, delivery_max_minutes, is_veg_only, area, lat, lng)
  values (${q(r.slug)}, ${q(r.name)}, ${arr(r.cuisine_tags)}, ${r.rating}, ${r.rating_count}, ${r.delivery_min_minutes}, ${r.delivery_max_minutes}, ${r.is_veg_only}, ${q(r.area)}, ${r.lat}, ${r.lng})
  returning id
)
insert into public.menu_items (restaurant_id, name, price_minor, is_veg, is_featured, sort_order, image_url)
select r.id, m.* from r, (values
${r.menu_items
  .map((m) => `  (${q(m.name)}, ${m.price_minor}, ${m.is_veg}, ${m.is_featured}, ${m.sort_order}, ${q(m.image_url)})`)
  .join(",\n")}
) as m(name, price_minor, is_veg, is_featured, sort_order, image_url);

`;
}

writeFileSync(join(root, "supabase/seed.sql"), sql);
console.log(`wrote supabase/seed.sql (${restaurants.length} restaurants)`);
